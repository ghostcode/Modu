export const translate: Record<Locale, (message: string, values?: Values) => string> = {
  "zh-CN": (message, values) => interpolate(message, values),
  en: (message, values) => interpolate(Object.hasOwn(english, message) ? english[message] : message, values),
};

function interpolate(message: string, values?: Values): string {
  return values ? message.replace(/\{(\d+)\}/g, (token, index) => String(values[Number(index)] ?? token)) : message;
}
